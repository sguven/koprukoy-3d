"""v1.23: caps on the terrain under the GLB road deck (src/roadbed_data.js, applied by src/roadbed.js).

The v0.6 GLB lays the D.260 dual carriageway as a concrete deck ("Beton" in Yollar) over a terrain that rises above
it in places, so the ground cut through the asphalt in jagged patches. For every terrain triangle that pokes through
the deck (raster of the deck's upward faces, 0.5 m cells) its three vertices are capped at the lowest deck height
over the triangle minus a clearance; a triangle's interior is a convex combination of its vertices, so it then stays
under the deck everywhere. Arazi vertices sit on the 8 m grid of data4.js, so their caps are written as grid nodes.
Usage: node tools/roadbed_dump.mjs /tmp/roadbed_dump.json && python3 tools/roadbed.py /tmp/roadbed_dump.json
"""
import json, math, sys, numpy as np
d = json.load(open(sys.argv[1]))
CLEAR = {'Arazi': 0.15, 'Arazi_Detay': 0.12}
g = d['grid']; cs = g['size'] / g['seg']; W1 = g['seg'] + 1
deck = [m for m in d['meshes'] if m['name'] == 'Beton']
# 1) raster of deck top height (0.5 m cells): max y of upward faces
C = 0.5
top = {}
for m in deck:
    P = np.array(m['pos']).reshape(-1, 3); I = np.array(m['idx']).reshape(-1, 3)
    for t in I:
        a, b, c = P[t]
        n = np.cross(b - a, c - a); L = np.linalg.norm(n)
        if L < 1e-9 or abs(n[1]) / L < 0.8: continue
        xs = [a[0], b[0], c[0]]; zs = [a[2], b[2], c[2]]
        for ix in range(int(math.floor(min(xs) / C)), int(math.ceil(max(xs) / C)) + 1):
            for iz in range(int(math.floor(min(zs) / C)), int(math.ceil(max(zs) / C)) + 1):
                x, z = ix * C, iz * C
                det = (b[2] - c[2]) * (a[0] - c[0]) + (c[0] - b[0]) * (a[2] - c[2])
                if abs(det) < 1e-12: continue
                l1 = ((b[2] - c[2]) * (x - c[0]) + (c[0] - b[0]) * (z - c[2])) / det
                l2 = ((c[2] - a[2]) * (x - c[0]) + (a[0] - c[0]) * (z - c[2])) / det
                l3 = 1 - l1 - l2
                if min(l1, l2, l3) < -1e-6: continue
                y = l1 * a[1] + l2 * b[1] + l3 * c[1]
                k = (ix, iz)
                if y > top.get(k, -1e9): top[k] = y
print('deck cells', len(top), file=sys.stderr)
def solve(m, clear, apply=True):
    P = np.array(m['pos']).reshape(-1, 3).copy(); I = np.array(m['idx']).reshape(-1, 3)
    lim = {}
    nviol = 0; worst = 0
    for t in I:
        a, b, c = P[t]
        xs = [a[0], b[0], c[0]]; zs = [a[2], b[2], c[2]]
        det = (b[2] - c[2]) * (a[0] - c[0]) + (c[0] - b[0]) * (a[2] - c[2])
        if abs(det) < 1e-12: continue
        viol = False; dmin = 1e9
        for ix in range(int(math.floor(min(xs) / C)), int(math.ceil(max(xs) / C)) + 1):
            for iz in range(int(math.floor(min(zs) / C)), int(math.ceil(max(zs) / C)) + 1):
                D = top.get((ix, iz))
                if D is None: continue
                x, z = ix * C, iz * C
                l1 = ((b[2] - c[2]) * (x - c[0]) + (c[0] - b[0]) * (z - c[2])) / det
                l2 = ((c[2] - a[2]) * (x - c[0]) + (a[0] - c[0]) * (z - c[2])) / det
                l3 = 1 - l1 - l2
                if min(l1, l2, l3) < -1e-6: continue
                y = l1 * a[1] + l2 * b[1] + l3 * c[1]
                if y > D - clear + 1e-3: viol = True; worst = max(worst, y - D + clear)
                dmin = min(dmin, D - clear)
        if viol:
            nviol += 1
            for v in t: lim[v] = min(lim.get(v, 1e9), dmin)
    return P, lim, nviol, worst
res = {'grid': {}, 'detail': []}
for m in d['meshes']:
    if m['parent'] not in ('Arazi', 'Arazi_Detay'): continue
    clear = CLEAR[m['parent']]
    P, lim, nv, worst = solve(m, clear)
    ch = {v: y for v, y in lim.items() if P[v][1] > y}
    for v, y in ch.items():
        x, yy, z = P[v]
        if m['parent'] == 'Arazi':
            fi = (x - g['x0']) / cs; fj = (z - g['z0']) / cs; ii, jj = round(fi), round(fj)
            if abs(fi - ii) > 0.03 or abs(fj - jj) > 0.03: print('off-grid vertex', x, z, file=sys.stderr); continue
            kk = ii + W1 * jj; res['grid'][kk] = min(res['grid'].get(kk, 1e9), math.floor(y * 100) / 100)
        else:
            res['detail'].append([round(x, 2), round(z, 2), math.floor(y * 100) / 100])
    print(m['parent'], 'tris violating', nv, 'worst', round(worst, 2), 'verts lowered', len(ch), 'max drop', round(max([P[v][1] - y for v, y in ch.items()] or [0]), 2), file=sys.stderr)
g2 = sorted((int(k), v) for k, v in res['grid'].items()); det = sorted(res['detail'])
open(sys.argv[2] if len(sys.argv) > 2 else 'src/roadbed_data.js', 'w').write('''// Generated by tools/roadbed.py (v1.23) from tools/roadbed_dump.mjs. Do not edit by hand.
// Caps on the ground under the GLB road deck (the D.260 carriageways, material "Beton"): the terrain stays at least
// 15 cm (fine overlay 12 cm) under the deck, so it no longer cuts through the asphalt in jagged patches.
// GRID_CAPS: [node index on the 8 m height grid of data4.js, max height]; DETAIL_CAPS: [x, z, max height] of
// Arazi_Detay vertices.
export const GRID_CAPS = %s;
export const DETAIL_CAPS = %s;
''' % (json.dumps([[k, v] for k, v in g2], separators=(',', ':')), json.dumps(det, separators=(',', ':'))))
